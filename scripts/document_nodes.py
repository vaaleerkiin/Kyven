"""Build the control reference from real Nuke nodes without running inference.

Run from the repository root with Nuke 16::

    Nuke16.0.exe --nukex -i -t scripts/document_nodes.py

This uses factory model defaults, ignoring the workstation's saved preferences.
It creates a new in-memory script; do not execute it in an artist's open script.
"""

from __future__ import annotations

import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "hosts/nuke"), str(ROOT / "src")]

import kyven_nuke  # noqa: F401 - serialized knob callbacks use this name
import nuke
from kyven_nuke import preferences

# No changes to preferences.json, installed models or an existing cache.
preferences.load_defaults = lambda: dict(preferences._FALLBACKS)

from kyven_nuke import (
    dlss_node,
    generative_fill_node,
    inpaint_node,
    node,
    refine_node,
)

# Headless documentation capture must not dispatch GUI-only Live timers.
dlss_node._schedule_live = lambda *args, **kwargs: None


def plain(value: object) -> str:
    text = html.unescape(re.sub(r"<[^>]+>", " ", str(value)))
    return " ".join(text.split()).replace("|", "\\|")


def menu_label(value: object, choices: list[str]) -> object:
    for choice in choices:
        stored, separator, label = choice.partition("\t")
        if separator and value == stored:
            return f"{label} (stored: {stored})"
    return value


def capture(current, standard: set[str]) -> dict:
    controls = []
    for knob in current.allKnobs():
        if knob.name() in standard or not knob.visible():
            continue
        if knob.Class() in {"Text_Knob", "Tab_Knob"}:
            continue
        resolved = current[knob.name()]
        choices = list(resolved.values()) if resolved.Class() == "Enumeration_Knob" else []
        action = (knob.Class() in {"PyScript_Knob", "Script_Knob"}
                  or knob.name().startswith("remove_"))
        value = "Action" if action else menu_label(resolved.value(), choices)
        choices = [choice.partition("\t")[2] if "\t" in choice else choice
                   for choice in choices]
        controls.append({"name": knob.name(), "label": plain(knob.label()) or knob.name(),
                         "value": value, "choices": choices, "help": plain(knob.tooltip())})
    inputs = sorted(
        ({"index": int(child["number"].value()), "label": child.name()}
         for child in current.nodes() if child.Class() == "Input"),
        key=lambda item: item["index"],
    )
    return {"name": current.name(), "inputs": inputs, "controls": controls}


def main() -> None:
    standard_node = nuke.nodes.Group()
    standard = set(standard_node.knobs())
    nuke.delete(standard_node)
    records = []
    factories = [
        ("Segment", "SEGMENT.md", node.create_segment_node),
        ("Refine", "REFINE.md", refine_node.create_refine_node),
        ("Inpaint", "INPAINT.md", inpaint_node.create_inpaint_node),
        ("Generative Fill / Mage", "GENERATIVE_FILL.md",
         generative_fill_node.create_generative_fill_node),
        ("DLSS", "DLSS.md", dlss_node.create_dlss_node),
    ]
    for title, guide, create in factories:
        for selected in nuke.selectedNodes():
            selected.setSelected(False)
        current = create()
        records.append((title, guide, capture(current, standard)))
        if title == "Generative Fill / Mage":
            for label in generative_fill_node.MODEL_LABELS[:1]:
                current["model"].setValue(label)
                generative_fill_node._ensure_model_control(current)
                current["steps"].setValue(20 if "Base" in label else 4)
                records.append((f"Generative Fill / {label}", guide, capture(current, standard)))

    nuke.pluginAddPath(str(ROOT / "plugins/Cattery/WAFT"))
    current = nuke.createNode("WAFT", inpanel=False)
    records.append(("WAFT SmartVector", "WAFT.md", capture(current, standard)))

    lines = ["# Nuke control reference", "",
             ("[Documentation home](README.md) · [Visual node guide](NODES.md) · "
              "[Shared workflow](NUKE.md)"), "",
             (f"Captured from new nodes in Nuke {nuke.NUKE_VERSION_STRING} with "
              "factory model preferences and no inputs. No inference was run."), "",
             ("Generated by [document_nodes.py](../scripts/document_nodes.py). "
              "Rerun with `Nuke16.0.exe --nukex -i -t scripts/document_nodes.py` "
              "after changing controls."), "",
             ("Tables list visible editable controls and buttons. A control may be disabled "
             "until its input or mode is available. Context-dependent controls can appear "
             "after changing a mode; use the linked task guide for their behavior. "
             "Saved scripts and Model Manager defaults can differ from these factory values."), ""]
    for title, guide, record in records:
        lines.extend([f"## {title}", "", f"[Task guide]({guide})", "",
                      "Inputs: " + ", ".join(f"`{i['index']}` {i['label']}" for i in record["inputs"])
                      + ".", "", "| Control | Initial value / action | What it does |",
                      "| --- | --- | --- |"])
        for item in record["controls"]:
            value = plain(item["value"])
            if len(value) > 100:
                value = "See editable text in node"
            help_text = item["help"]
            if item["choices"]:
                help_text += " Choices: " + "; ".join(plain(v) for v in item["choices"]) + "."
            lines.append(f"| **{item['label']}** (`{item['name']}`) | {value or 'Empty'} | {help_text} |")
        lines.append("")
    (ROOT / "docs/NODE_CONTROLS.md").write_text("\n".join(lines), encoding="utf-8")
    report = ROOT / ".runtime/documentation-capture/nodes.json"
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(json.dumps({"nuke": nuke.NUKE_VERSION_STRING, "nodes": records},
                                 indent=2, default=str), encoding="utf-8")
    print(f"Documented {len(records)} node/model layouts: {report}", flush=True)


if __name__ == "__main__":
    main()
